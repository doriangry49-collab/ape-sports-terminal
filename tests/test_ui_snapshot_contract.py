class TestSnapshotEdgeSchemaContract:

    def test_edges_exist_across_fixtures(self, exported_snapshot):
        total_edges = sum(len(f.get("edges", [])) for f in exported_snapshot["fixtures"])
        assert total_edges > 0, "Snapshot must contain calculated edges"

    def test_edge_fields_contract(self, exported_snapshot):
        required_edge_fields = [
            "bookmaker",
            "market",
            "selection",
            "selection_display",
            "entry_odds",
            "raw_implied",
            "overround",
            "market_fair_odds",
            "fair_odds_shin",
            "model_prob",
            "raw_edge",
            "shin_margin",
            "ev_roi",
            "half_kelly",
            "kickoff_trt",
            "league",
            "competition",
        ]

        edge_count = 0
        for f in exported_snapshot["fixtures"]:
            f_comp = f["competition"]
            for e in f.get("edges", []):
                edge_count += 1
                for field in required_edge_fields:
                    assert field in e, f"Edge missing required field '{field}' in fixture {f['fixture_id']}"

                # Data type and range assertions
                assert isinstance(e["entry_odds"], (int, float)) and e["entry_odds"] > 1.0
                assert isinstance(e["ev_roi"], (int, float))
                assert isinstance(e["half_kelly"], (int, float)) and e["half_kelly"] >= 0.0
                assert isinstance(e["shin_margin"], (int, float)) and e["shin_margin"] > 0.0
                assert isinstance(e["fair_odds_shin"], (int, float)) and e["fair_odds_shin"] > 1.0

                # League consistency
                assert e["league"] == f_comp or e["league"] == e["competition"]
                assert e["competition"] == f_comp or e["competition"] == e["league"]
                assert len(e["league"].strip()) > 0

        assert edge_count > 0


