class TestSnapshotRootSchemaContract:

    def test_root_required_keys_present(self, exported_snapshot):
        required_keys = [
            "engine_name",
            "engine_version",
            "snapshot_timestamp",
            "data_cutoff",
            "provider",
            "match_phase",
            "daemon_status",
            "provider_status",
            "total_fixtures",
            "total_edges_calculated",
            "fixtures",
        ]
        for key in required_keys:
            assert key in exported_snapshot, f"Root snapshot missing key: {key}"

    def test_root_engine_metadata(self, exported_snapshot):
        assert exported_snapshot["engine_name"] == "Sports Intelligence Terminal"
        assert "quant" in exported_snapshot["engine_version"].lower() or "v2" in exported_snapshot["engine_version"]
        assert isinstance(exported_snapshot["provider"], str)
        assert isinstance(exported_snapshot["match_phase"], str)

    def test_root_timestamps_iso_valid(self, exported_snapshot):
        # Validate ISO 8601 parsing
        ts = datetime.fromisoformat(exported_snapshot["snapshot_timestamp"])
        assert ts.tzinfo is not None, "Timestamp must be timezone-aware"

        cutoff = datetime.fromisoformat(exported_snapshot["data_cutoff"])
        assert cutoff.tzinfo is not None

    def test_daemon_status_schema(self, exported_snapshot):
        ds = exported_snapshot["daemon_status"]
        assert isinstance(ds, dict)
        assert ds.get("status") in ("HEALTHY", "DEGRADED", "ONLINE")
        assert isinstance(ds.get("leagues_scanned"), int)
        assert ds.get("leagues_scanned") >= 0
        assert isinstance(ds.get("positive_ev_signals"), int)
        assert ds.get("positive_ev_signals") >= 0

    def test_provider_status_schema(self, exported_snapshot):
        ps = exported_snapshot["provider_status"]
        assert isinstance(ps, list)
        assert len(ps) >= 1
        for p in ps:
            assert "provider" in p
            assert "status" in p
            assert "events" in p
            assert "reconciliation" in p

    def test_total_counters_consistency(self, exported_snapshot):
        fixtures = exported_snapshot["fixtures"]
        assert exported_snapshot["total_fixtures"] == len(fixtures)
        expected_edges = sum(len(f.get("edges", [])) for f in fixtures)
        assert exported_snapshot["total_edges_calculated"] == expected_edges


